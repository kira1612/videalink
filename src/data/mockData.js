// Generate time-series chart data
export const generateChartData = (points = 20, baseValue = 25, variance = 5) => {
  const now = Date.now();
  return Array.from({ length: points }, (_, i) => ({
    time: new Date(now - (points - i) * 60000).toLocaleTimeString('id-ID', {
      hour: '2-digit',
      minute: '2-digit',
    }),
    value: parseFloat((baseValue + (Math.random() - 0.5) * variance * 2).toFixed(1)),
  }));
};

